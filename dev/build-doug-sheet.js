/* ==========================================================================
   Doug character sheet generator
   --------------------------------------------------------------------------
   Renders every mood, in both themes, to a single standalone HTML file you can
   open straight from disk. Reviewing a character system side by side is the
   only way to catch a mood that's drifted off-model.

   Self-contained on purpose: ES modules are blocked over file://, so the CSS
   gets inlined rather than linked, and this becomes a file you can just
   double-click.

     npm run doug   ->   dev/doug-sheet.html

   That dougSVG() runs unmodified in node — no DOM, no chrome.* — is the same
   property that makes the logic modules unit-testable (DESIGN.md ADR-8).
   ========================================================================== */

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { MOODS, dougSVG } from '../src/shared/doug.js';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..');

const read = (p) => readFileSync(join(root, p), 'utf8');

// Font URLs in tokens.css are relative to src/shared/; this page sits in dev/.
const tokens = read('src/shared/tokens.css').replaceAll('../../assets/', '../assets/');
const dougCss = read('src/shared/doug.css');

const moodIds = Object.keys(MOODS);

const card = (mood) => `
  <figure class="card">
    <div class="card__stage">${dougSVG(mood)}</div>
    <figcaption>
      <span class="card__name">${MOODS[mood].label}</span>
      <code class="card__id">${mood}</code>
      <span class="card__why">${MOODS[mood].because}</span>
    </figcaption>
  </figure>`;

const panel = (theme) => `
  <section class="panel" data-theme="${theme}">
    <div class="panel__inner">
      <h2 class="panel__title label">${theme}</h2>
      <div class="grid">${moodIds.map(card).join('')}</div>
      <div class="scales">
        <div class="scale"><div class="scale__box" style="width:220px">${dougSVG('chill')}</div><span class="label">220px</span></div>
        <div class="scale"><div class="scale__box" style="width:92px">${dougSVG('chill')}</div><span class="label">92px — popup</span></div>
        <div class="scale"><div class="scale__box" style="width:40px">${dougSVG('chill', { breathing: false })}</div><span class="label">40px</span></div>
      </div>
    </div>
  </section>`;

const html = `<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="UTF-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Doug — character sheet</title>
<style>
${tokens}
${dougCss}

/* --- sheet chrome (dev only, not part of the product) --- */
body { background: var(--paper); }
body::after { display: none; }

.masthead {
  padding: var(--space-5) var(--space-6);
  border-bottom: 1px solid var(--rule);
  display: flex; align-items: baseline; gap: var(--space-4);
}
.masthead h1 {
  margin: 0;
  font-family: var(--font-display);
  font-variation-settings: var(--display-opsz-mid);
  font-size: var(--text-lg); font-weight: 700;
  letter-spacing: var(--tracking-tight);
}
.masthead p { margin: 0; color: var(--ink-faint); font-size: var(--text-sm); }

.panel { background: var(--paper); color: var(--ink); }
.panel__inner { padding: var(--space-6); max-width: 1100px; margin: 0 auto; }
.panel__title { display: block; margin: 0 0 var(--space-5); }

.grid {
  display: grid;
  grid-template-columns: repeat(auto-fill, minmax(190px, 1fr));
  gap: var(--space-4);
}

.card {
  margin: 0;
  border: 1px solid var(--rule);
  border-radius: var(--radius-lg);
  background: var(--paper-raised);
  overflow: hidden;
}
.card__stage {
  padding: var(--space-4);
  background: radial-gradient(circle at 45% 42%, var(--moss-wash) 0%, transparent 70%);
}
.card figcaption {
  display: grid; gap: 2px;
  padding: var(--space-3) var(--space-4);
  border-top: 1px solid var(--rule);
}
.card__name {
  font-family: var(--font-display);
  font-variation-settings: var(--display-opsz-low);
  font-weight: 700; font-size: var(--text-md);
}
.card__id { font-family: var(--font-mono); font-size: var(--text-xs); color: var(--moss); }
.card__why { font-size: var(--text-sm); color: var(--ink-soft); }

.scales {
  display: flex; align-items: flex-end; gap: var(--space-6);
  margin-top: var(--space-6); padding-top: var(--space-5);
  border-top: 1px solid var(--rule);
}
.scale { display: grid; gap: var(--space-2); justify-items: center; }
</style>
</head>
<body>
  <header class="masthead">
    <h1>Doug — character sheet</h1>
    <p>${moodIds.length} moods · generated by <code>npm run doug</code> · not shipped</p>
  </header>
  ${panel('light')}
  ${panel('dark')}
</body>
</html>
`;

const out = join(here, 'doug-sheet.html');
writeFileSync(out, html, 'utf8');
console.log(`Wrote ${out}\n${moodIds.length} moods x 2 themes. Open it in a browser.`);
